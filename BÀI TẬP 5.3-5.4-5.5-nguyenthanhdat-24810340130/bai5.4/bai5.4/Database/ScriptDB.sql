-- UTF-16 hex literals keep Vietnamese text intact across SQL client code pages.
IF OBJECT_ID(N'dbo.Phong', N'U') IS NULL
BEGIN
	CREATE TABLE dbo.Phong
	(
		SoPhong varchar(10) NOT NULL CONSTRAINT PK_Phong PRIMARY KEY,
		LoaiPhong nvarchar(50) NOT NULL,
		GiaTheoGio decimal(18,2) NOT NULL CONSTRAINT CK_Phong_GiaTheoGio CHECK (GiaTheoGio >= 0),
		TrangThai nvarchar(30) NOT NULL CONSTRAINT DF_Phong_TrangThai DEFAULT (CONVERT(nvarchar(30), 0x54007200D11E6E006700)),
		CONSTRAINT CK_Phong_TrangThai CHECK (TrangThai IN (
			CONVERT(nvarchar(30), 0x54007200D11E6E006700),
			CONVERT(nvarchar(30), 0x100161006E0067002000DF1E),
			CONVERT(nvarchar(30), 0x100161006E00670020006400CD1E6E0020006400B91E7000)))
	);
END;
GO

IF OBJECT_ID(N'dbo.KhachHang', N'U') IS NULL
BEGIN
	CREATE TABLE dbo.KhachHang
	(
		MaKH int IDENTITY(1,1) NOT NULL CONSTRAINT PK_KhachHang PRIMARY KEY,
		HoTen nvarchar(100) NOT NULL,
		CCCD varchar(20) NOT NULL,
		SoDienThoai varchar(15) NULL,
		CONSTRAINT UQ_KhachHang_CCCD UNIQUE (CCCD)
	);
END;
GO

IF OBJECT_ID(N'dbo.DichVu', N'U') IS NULL
BEGIN
	CREATE TABLE dbo.DichVu
	(
		MaDV int IDENTITY(1,1) NOT NULL CONSTRAINT PK_DichVu PRIMARY KEY,
		TenDV nvarchar(100) NOT NULL,
		DonGia decimal(18,2) NOT NULL CONSTRAINT CK_DichVu_DonGia CHECK (DonGia >= 0)
	);
END;
GO

IF OBJECT_ID(N'dbo.PhieuDatPhong', N'U') IS NULL
BEGIN
	CREATE TABLE dbo.PhieuDatPhong
	(
		MaPhieu int IDENTITY(1,1) NOT NULL CONSTRAINT PK_PhieuDatPhong PRIMARY KEY,
		SoPhong varchar(10) NOT NULL,
		MaKH int NOT NULL,
		NgayNhanPhong datetime NOT NULL CONSTRAINT DF_PhieuDatPhong_NgayNhan DEFAULT (GETDATE()),
		NgayTraPhong datetime NULL,
		TongTienThanhToan decimal(18,2) NULL,
		CONSTRAINT FK_PhieuDatPhong_Phong FOREIGN KEY (SoPhong) REFERENCES dbo.Phong(SoPhong),
		CONSTRAINT FK_PhieuDatPhong_KhachHang FOREIGN KEY (MaKH) REFERENCES dbo.KhachHang(MaKH)
	);
END;
GO

IF OBJECT_ID(N'dbo.SuDungDichVu', N'U') IS NULL
BEGIN
	CREATE TABLE dbo.SuDungDichVu
	(
		MaSuDung int IDENTITY(1,1) NOT NULL CONSTRAINT PK_SuDungDichVu PRIMARY KEY,
		MaPhieu int NOT NULL,
		MaDV int NOT NULL,
		SoLuong int NOT NULL CONSTRAINT CK_SuDungDichVu_SoLuong CHECK (SoLuong > 0),
		ThoiGian datetime NOT NULL CONSTRAINT DF_SuDungDichVu_ThoiGian DEFAULT (GETDATE()),
		CONSTRAINT FK_SuDungDichVu_Phieu FOREIGN KEY (MaPhieu) REFERENCES dbo.PhieuDatPhong(MaPhieu),
		CONSTRAINT FK_SuDungDichVu_DichVu FOREIGN KEY (MaDV) REFERENCES dbo.DichVu(MaDV)
	);
END;
GO

IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = N'CK_Phong_TrangThai' AND parent_object_id = OBJECT_ID(N'dbo.Phong'))
BEGIN
	ALTER TABLE dbo.Phong DROP CONSTRAINT CK_Phong_TrangThai;
END;
GO

IF EXISTS (SELECT 1 FROM sys.default_constraints WHERE name = N'DF_Phong_TrangThai' AND parent_object_id = OBJECT_ID(N'dbo.Phong'))
BEGIN
	ALTER TABLE dbo.Phong DROP CONSTRAINT DF_Phong_TrangThai;
END;
GO

